function random(min, max) {
  return Math.floor(Math.random() * (max - min + 1)) + min;
}

function randomFloat(min, max) {
  return +(Math.random() * (max - min) + min).toFixed(1);
}

function pick(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}

function splitHours(total) {
  const entries = [];

  let remaining = total;

  while (remaining > 0.5) {
    const chunk = Math.min(
      remaining,
      randomFloat(1.0, 3.5)
    );

    entries.push(+chunk.toFixed(1));

    remaining = +(remaining - chunk).toFixed(1);
  }

  return entries;
}

function getDailyHours(user) {

  if (user.role === "System-Admin") {
    return randomFloat(1, 3);
  }

  if (
    user.role &&
    user.role.toLowerCase().includes("lead")
  ) {
    return randomFloat(3, 5);
  }

  return randomFloat(5, 7);
}

export function generateMockTimeEntries(
  users,
  tasks
) {

  let entryCounter = 1;

  const entries = [];

  users.forEach(user => {
    const userTasks = tasks.filter(
      task =>
        task.assignedTo === user.id &&
        task.status !== "Backlog"
    );

    if (userTasks.length === 0) return;

    const descriptions =
      WORK_DESCRIPTIONS[user.department] ||
      WORK_DESCRIPTIONS.Engineering;

    WORKING_DAYS.forEach(day => {
      const dailyHours =
        getDailyHours(user);

      const chunks =
        splitHours(dailyHours);

      let startHour = 9;

      chunks.forEach((chunk, index) => {
        const task = userTasks[index % userTasks.length];

        const startH = Math.floor(startHour);
        const startM = Math.round((startHour - startH) * 60);
        const startTime = `${String(startH).padStart(2, "0")}:${String(startM).padStart(2, "0")}`;

        const endHour = startHour + chunk;
        const endH = Math.floor(endHour);
        const endM = Math.round((endHour - endH) * 60);
        const endTime = `${String(endH).padStart(2, "0")}:${String(endM).padStart(2, "0")}`;

        entries.push({
          id: `entry-${entryCounter++}`,
          userId: user.id,
          taskId: task.id,
          projectId: task.projectId,
          description: pick(descriptions),
          date: day,
          startTime,
          endTime,
          duration: chunk.toString(),
          status: "Approved",
          workCategory: task.type,
          justification: ""
        });

        startHour = endHour + 0.5;
      });
    });
  });

  return entries;
}


function randomTime(hour, minRange = 20) {
  return `${String(hour).padStart(2, "0")}:${String(
    random(0, minRange)
  ).padStart(2, "0")}:00Z`;
}

